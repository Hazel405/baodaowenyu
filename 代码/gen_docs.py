def fig(doc, path, width_cm=11.5, caption=None):
    from docx.shared import Cm
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.keep_together = True        # 图片不跨页截断
    p.paragraph_format.keep_with_next = True       # 与图题同页
    run = p.add_run()
    try:
        run.add_picture(path, width=Cm(width_cm))
    except Exception as e:
        p.add_run(f"[图片缺失: {path}]")
    if caption:
        para(doc, caption, size=10.5, align=WD_ALIGN_PARAGRAPH.CENTER, indent=False)


def table(doc, headers, rows, widths=None, size=10.5):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, htxt in enumerate(headers):
        c = t.rows[0].cells[j]
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = c.paragraphs[0].add_run(htxt)
        set_run(r, size, bold=True)
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            c = t.rows[i + 1].cells[j]
            r = c.paragraphs[0].add_run(str(val))
            set_run(r, size)
    return t


